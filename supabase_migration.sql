-- =====================================================
-- MIGRATION: Tambah kolom dan tabel untuk fitur baru
-- Jalankan di Supabase > SQL Editor
-- =====================================================

-- 1. Tambah kolom is_archived ke products (Soft Delete)
ALTER TABLE public.products
  ADD COLUMN IF NOT EXISTS is_archived BOOLEAN NOT NULL DEFAULT false;

-- 2. Tambah kolom images ke products (Multiple Images)
ALTER TABLE public.products
  ADD COLUMN IF NOT EXISTS images JSONB NOT NULL DEFAULT '[]'::jsonb;

-- 3. Tabel cart (Keranjang belanja)
CREATE TABLE IF NOT EXISTS public.cart (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    user_id UUID NOT NULL,
    product_id BIGINT NOT NULL
        REFERENCES public.products(id) ON DELETE CASCADE,
    quantity INTEGER NOT NULL DEFAULT 1 CHECK (quantity > 0),
    created_at TIMESTAMPTZ NOT NULL DEFAULT NOW(),
    UNIQUE (user_id, product_id)
);

-- 4. Tabel review_votes (Thumbs Up/Down)
CREATE TABLE IF NOT EXISTS public.review_votes (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    review_id BIGINT NOT NULL
        REFERENCES public.reviews(id) ON DELETE CASCADE,
    user_id UUID NOT NULL,
    vote INTEGER NOT NULL CHECK (vote IN (1, -1)),
    created_at TIMESTAMPTZ NOT NULL DEFAULT NOW(),
    UNIQUE (review_id, user_id)
);

-- 5. Drop FK constraints agar user_id bisa UUID lokal tanpa auth Supabase
ALTER TABLE public.cart DROP CONSTRAINT IF EXISTS cart_user_id_fkey;
ALTER TABLE public.review_votes DROP CONSTRAINT IF EXISTS review_votes_user_id_fkey;

-- 6. Enable RLS
ALTER TABLE public.cart ENABLE ROW LEVEL SECURITY;
ALTER TABLE public.review_votes ENABLE ROW LEVEL SECURITY;

-- 7. Grant access
GRANT SELECT, INSERT, UPDATE, DELETE ON public.cart TO anon, authenticated;
GRANT SELECT, INSERT, UPDATE, DELETE ON public.review_votes TO anon, authenticated;
GRANT USAGE, SELECT ON SEQUENCE public.cart_id_seq TO anon, authenticated;
GRANT USAGE, SELECT ON SEQUENCE public.review_votes_id_seq TO anon, authenticated;

-- 8. Drop old policies if exist
DROP POLICY IF EXISTS "Allow public all on cart" ON public.cart;
DROP POLICY IF EXISTS "Allow authenticated all on cart" ON public.cart;
DROP POLICY IF EXISTS "Allow public all on review_votes" ON public.review_votes;
DROP POLICY IF EXISTS "Allow authenticated all on review_votes" ON public.review_votes;

-- 9. Create open policies
CREATE POLICY "Allow public all on cart"
ON public.cart FOR ALL TO anon USING (true) WITH CHECK (true);

CREATE POLICY "Allow authenticated all on cart"
ON public.cart FOR ALL TO authenticated USING (true) WITH CHECK (true);

CREATE POLICY "Allow public all on review_votes"
ON public.review_votes FOR ALL TO anon USING (true) WITH CHECK (true);

CREATE POLICY "Allow authenticated all on review_votes"
ON public.review_votes FOR ALL TO authenticated USING (true) WITH CHECK (true);
